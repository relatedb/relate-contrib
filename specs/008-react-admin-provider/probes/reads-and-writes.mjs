import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
const req = createRequire(new URL("../../../packages/web/package.json", import.meta.url));
const dir = dirname(req.resolve("@relate/relate-wasm"));
const mod = await import(join(dir, "relate.js"));
await mod.default({ module_or_path: readFileSync(join(dir, "relate_bg.wasm")) });
const db = new mod.RelateDb();
const run = (label, q, p) => {
  const env = JSON.parse(db.execute(q, p ? JSON.stringify(p) : null));
  console.log(`\n## ${label}\n${q}\n->`, env.error ? "ERROR: " + env.error : JSON.stringify(env.rows).slice(0, 400), env.error ? "" : `(cols ${JSON.stringify(env.columns)})`);
  return env;
};
run("seed", `CREATE (:Company {id:'c1', name:'Acme', size:10}), (:Company {id:'c2', name:'Beta', size:20}),
 (:Person {id:'p1', name:'Ada', age:30}), (:Person {id:'p2', name:'ada Lovelace', age:30}), (:Person {id:'p3', name:'Bo', age:41})`);
run("rels", `MATCH (p:Person {id:'p1'}), (c:Company {id:'c1'}) CREATE (p)-[:WORKS_AT]->(c)`);
run("RETURN n", `MATCH (p:Person {id:$id}) RETURN p`, { id: "p1" });
run("skip/limit params", `MATCH (p:Person) RETURN p.id AS id ORDER BY p.age ASC, p.id ASC SKIP $skip LIMIT $limit`, { skip: 1, limit: 2 });
run("contains ci", `MATCH (p:Person) WHERE toLower(p.name) CONTAINS toLower($q) RETURN p.id AS id`, { q: "ADA" });
run("range number", `MATCH (p:Person) WHERE p.age >= $v RETURN p.id AS id`, { v: 31 });
run("range string vs number (mixed)", `MATCH (p:Person) WHERE p.name >= $v RETURN p.id AS id`, { v: 5 });
run("membership", `MATCH (p:Person) WHERE p.id IN $ids RETURN p.id AS id`, { ids: ["p1", "p3"] });
run("reference fill", `MATCH (p:Person) OPTIONAL MATCH (p)-[:WORKS_AT]->(c:Company) RETURN p, c.id AS company ORDER BY p.id`);
run("replace rel one statement", `MATCH (p:Person {id:$id}) OPTIONAL MATCH (p)-[r:WORKS_AT]->(:Company) DELETE r WITH DISTINCT p MATCH (c:Company {id:$cid}) CREATE (p)-[:WORKS_AT]->(c) RETURN p.id AS id`, { id: "p1", cid: "c2" });
run("check", `MATCH (p:Person {id:'p1'})-[r:WORKS_AT]->(c) RETURN c.id AS c, count(r) AS n`);
run("replace rel, target missing", `MATCH (p:Person {id:$id}) OPTIONAL MATCH (p)-[r:WORKS_AT]->(:Company) DELETE r WITH DISTINCT p MATCH (c:Company {id:$cid}) CREATE (p)-[:WORKS_AT]->(c) RETURN p.id AS id`, { id: "p1", cid: "nope" });
run("check after missing-target (was rel lost?)", `MATCH (p:Person {id:'p1'})-[r:WORKS_AT]->(c) RETURN c.id AS c`);
run("create with missing target", `MATCH (c:Company {id:$cid}) CREATE (p:Person {id:$id, name:$name}) CREATE (p)-[:WORKS_AT]->(c) RETURN p.id AS id`, { cid: "nope", id: "p9", name: "X" });
run("exists p9?", `MATCH (p:Person {id:'p9'}) RETURN count(p) AS n`);
run("SET += map", `MATCH (p:Person {id:$id}) SET p += $props RETURN p.name AS name, p.age AS age`, { id: "p3", props: { name: "Bob", age: 42 } });
run("null in map set", `MATCH (p:Person {id:$id}) SET p += $props RETURN p`, { id: "p3", props: { age: null } });
run("count", `MATCH (p:Person) WHERE p.age >= $v RETURN count(p) AS total`, { v: 0 });
run("order by with nulls", `MATCH (p:Person) RETURN p.id AS id, p.age AS age ORDER BY p.age ASC, p.id ASC`);
run("detach delete count", `MATCH (c:Company {id:$id}) DETACH DELETE c RETURN count(c) AS n`, { id: "c2" });
run("delete missing", `MATCH (c:Company {id:$id}) DETACH DELETE c RETURN count(c) AS n`, { id: "zzz" });
run("quoted identifier", "MATCH (p:Person) RETURN p.`name` AS `name` ORDER BY p.`name` ASC", null);
run("injection param", `MATCH (p:Person) WHERE p.name = $v RETURN p.id AS id`, { v: `x" RETURN 1 //` });
run("labels/type", `MATCH (p:Person {id:'p1'}) RETURN labels(p) AS l, elementId(p) AS e`);
run("duplicate id create?", `CREATE (:Person {id:'p1', name:'dup'})`);
